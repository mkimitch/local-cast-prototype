import {chromium} from '@playwright/test';

const origin = process.env.LOCALCAST_LIVE_URL;
const episodeId = process.env.LOCALCAST_LIVE_EPISODE_ID;
if (!origin || !episodeId) {
	throw new Error('LOCALCAST_LIVE_URL and LOCALCAST_LIVE_EPISODE_ID are required');
}

const externalOrigins = new Set();
const browser = await chromium.launch({headless: true});
try {
	const context = await browser.newContext();
	const page = await context.newPage();
	page.on('request', request => {
		const requestOrigin = new URL(request.url()).origin;
		if (requestOrigin !== new URL(origin).origin) externalOrigins.add(requestOrigin);
	});
	await page.goto(`${origin}/episodes/${encodeURIComponent(episodeId)}`);
	await page.getByRole('region', {name: 'AI-generated LocalCast audio'}).waitFor();
	await page.getByText('This voice and audio were generated by AI from the cited supplied material.').waitFor();
	const audio = page.locator('audio').first();
	await audio.waitFor();
	await audio.evaluate(element => {
		window.__localcastMediaEvents = [];
		for (const eventName of ['loadedmetadata', 'play', 'playing', 'pause', 'seeking', 'seeked', 'timeupdate', 'ended', 'error']) {
			element.addEventListener(eventName, () => window.__localcastMediaEvents.push(eventName));
		}
		if (element.readyState >= 1) window.__localcastMediaEvents.push('loadedmetadata');
	});
	await page.waitForFunction(() => document.querySelector('audio')?.readyState >= 1);
	const duration = await audio.evaluate(element => element.duration);
	if (!Number.isFinite(duration) || duration < 60 || duration > 90) throw new Error('Browser metadata duration is outside the listening gate');

	await audio.evaluate(element => element.play());
	await page.waitForFunction(() => {
		const element = document.querySelector('audio');
		return Boolean(element && !element.paused && element.currentTime > 0.25);
	});
	await audio.evaluate(element => element.pause());
	await page.waitForFunction(() => window.__localcastMediaEvents.includes('pause'));
	await audio.evaluate(element => { element.currentTime = Math.min(5, element.duration / 2); });
	await page.waitForFunction(() => window.__localcastMediaEvents.includes('seeked'));

	const mediaEvents = await page.evaluate(() => [...window.__localcastMediaEvents]);
	const requiredEvents = ['loadedmetadata', 'play', 'playing', 'pause', 'seeking', 'seeked', 'timeupdate'];
	if (requiredEvents.some(eventName => !mediaEvents.includes(eventName)) || mediaEvents.includes('error')) {
		throw new Error('Native media event verification failed');
	}
	const citationCount = await page.locator('blockquote').count();
	if (citationCount < 1) throw new Error('Resolved citations were not rendered');

	await page.reload();
	await page.getByRole('region', {name: 'AI-generated LocalCast audio'}).waitFor();
	await page.getByRole('link', {name: 'Episodes'}).click();
	await page.goBack();
	await page.getByRole('region', {name: 'AI-generated LocalCast audio'}).waitFor();

	const storage = await page.evaluate(() => ({local: Object.keys(localStorage), session: Object.keys(sessionStorage)}));
	if (JSON.stringify(storage).match(/api.?key|authorization|credential/i)) throw new Error('Browser storage contained a credential-shaped key');
	if (externalOrigins.size > 0) throw new Error('The browser contacted a third-party origin');

	console.log(`browser_duration_seconds=${duration.toFixed(3)}`);
	console.log(`browser_media_events=${requiredEvents.join(',')}`);
	console.log(`resolved_citations=${citationCount}`);
	console.log('external_browser_origins=0');
	console.log('browser_credential_fields=0');
} finally {
	await browser.close();
}
